// MARK: - Локальный арт для новых ключей каталога
//
// В бандле лежит экспорт СТАРОГО каталога (c01…c29 + превью p01…p29). Новые
// ключи (kg01, dv01, …) на него не ложатся, поэтому держим таблицу соответствия:
// без неё карты без MinIO-имени остались бы вообще без картинки.
// Коллекции, которых в старом экспорте не было (Мекеним, Мемы, Талисманы,
// Цитаты, Көчмөн мурас и часть Кыргызстана), локального арта не имеют —
// они грузятся только из MinIO.
enum LegacyArt {
    static let map: [String: String] = [
        "kg01": "c11",
        "kg02": "c12",
        "kg03": "c13",
        "kg04": "c14",
        "kg05": "c15",
        "kg06": "c16",
        "kg07": "c17",
        "kg08": "c18",
        "dv01": "c06",
        "dv02": "c07",
        "dv03": "c08",
        "dv04": "c09",
        "dv05": "c10",
        "et01": "c01",
        "et02": "c02",
        "et03": "c03",
        "et04": "c04",
        "et05": "c05",
    ]

    /// Имя файла арта в бандле для ключа каталога (nil — локального нет).
    static func assetName(for key: String) -> String? { map[key] }

    /// Круглое превью для карусели (pNN), если есть.
    static func previewName(for key: String) -> String? {
        guard let a = map[key] else { return nil }
        return "p" + a.dropFirst()
    }
}
